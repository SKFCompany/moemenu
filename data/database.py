    def what_can_i_cook(self):
        fridge = {r["name"].lower() for r in self.get_fridge()}
        all_recipes = self.get_all_recipes()
        can_cook, partial = [], []
        for recipe in all_recipes:
            ingr = [i.strip().lower() for i in recipe["ingredients"].split("|") if i.strip()]
            if not ingr:
                continue
            matched = sum(1 for i in ingr if any(f in i or i in f for f in fridge))
            total = len(ingr)
            if matched >= total:
                can_cook.append(recipe)
            elif matched >= max(2, total // 2):
                missing = [i for i in ingr if not any(f in i or i in f for f in fridge)]
                partial.append({"recipe": recipe, "missing": missing})
        return can_cook, partial

