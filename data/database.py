CURRENT_SEED_VERSION = 5


class Database:
    def __init__(self):
        self.db_path = DB_PATH

    def get_conn(self):
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        return conn

    def init_db(self):
        conn = self.get_conn()
        c = conn.cursor()
        c.executescript("""
        CREATE TABLE IF NOT EXISTS recipes (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            name        TEXT NOT NULL,
            category    TEXT DEFAULT 'Основное',
            cuisine     TEXT DEFAULT 'Европейская',
            calories    INTEGER DEFAULT 0,
            cook_time   INTEGER DEFAULT 30,
            servings    INTEGER DEFAULT 2,
            image_url   TEXT DEFAULT '',
            emoji       TEXT DEFAULT '🍽',
            ingredients TEXT DEFAULT '',
            steps       TEXT DEFAULT '',
            is_favorite INTEGER DEFAULT 0,
            is_custom   INTEGER DEFAULT 0,
            created_at  TEXT DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS meal_plan (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            plan_date   TEXT NOT NULL,
            meal_type   TEXT NOT NULL,
            recipe_id   INTEGER,
            recipe_name TEXT,
            UNIQUE(plan_date, meal_type)
        );

        CREATE TABLE IF NOT EXISTS cook_history (
            id           INTEGER PRIMARY KEY AUTOINCREMENT,
            recipe_id    INTEGER,
            recipe_name  TEXT,
            recipe_emoji TEXT DEFAULT 'Основное',
            meal_type    TEXT,
            cooked_at    TEXT DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS fridge (
            id        INTEGER PRIMARY KEY AUTOINCREMENT,
            name      TEXT UNIQUE NOT NULL,
            quantity  TEXT DEFAULT '',
            added_at  TEXT DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS shopping_list (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            name        TEXT NOT NULL,
            quantity    TEXT DEFAULT '',
            is_checked  INTEGER DEFAULT 0,
            added_at    TEXT DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS meta (
            key   TEXT PRIMARY KEY,
            value TEXT
        );
        """)

        # ── Миграция: добавляем колонки если их нет (старая БД) ──
        existing = {row[1] for row in c.execute("PRAGMA table_info(recipes)")}
        if "cuisine" not in existing:
            c.execute("ALTER TABLE recipes ADD COLUMN cuisine TEXT DEFAULT 'Европейская'")
        if "image_url" not in existing:
            c.execute("ALTER TABLE recipes ADD COLUMN image_url TEXT DEFAULT ''")
        if "emoji" not in existing:
            c.execute("ALTER TABLE recipes ADD COLUMN emoji TEXT DEFAULT '🍽'")
        if "is_custom" not in existing:
            c.execute("ALTER TABLE recipes ADD COLUMN is_custom INTEGER DEFAULT 0")
        if "protein" not in existing:
            c.execute("ALTER TABLE recipes ADD COLUMN protein REAL DEFAULT 0")
        if "fat" not in existing:
            c.execute("ALTER TABLE recipes ADD COLUMN fat REAL DEFAULT 0")
        if "carbs" not in existing:
            c.execute("ALTER TABLE recipes ADD COLUMN carbs REAL DEFAULT 0")
        if "difficulty" not in existing:
            c.execute("ALTER TABLE recipes ADD COLUMN difficulty TEXT DEFAULT 'Средний'")
        if "tags" not in existing:
            c.execute("ALTER TABLE recipes ADD COLUMN tags TEXT DEFAULT ''")

        conn.commit()
        conn.close()

    def _get_meta(self, c, key, default=None):
        c.execute("SELECT value FROM meta WHERE key = ?", (key,))
        row = c.fetchone()
        return row["value"] if row else default

    def _set_meta(self, c, key, value):
        c.execute(
            "INSERT INTO meta (key, value) VALUES (?,?) "
            "ON CONFLICT(key) DO UPDATE SET value = excluded.value",
            (key, str(value)),
        )

    def get_setting(self, key, default=None):
        """Публичный доступ к настройкам приложения (напр. тема оформления),
        хранящимся в той же таблице meta. В отличие от _get_meta/_set_meta,
        сам открывает и закрывает соединение — можно звать откуда угодно."""
        conn = self.get_conn()
        c = conn.cursor()
        value = self._get_meta(c, key, default)
        conn.close()
        return value

    def set_setting(self, key, value):
        conn = self.get_conn()
        c = conn.cursor()
        self._set_meta(c, key, value)
        conn.commit()
        conn.close()

