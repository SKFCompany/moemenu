    def get_all_recipes(self, search="", category="Все блюда", cuisine="Все кухни", tag=None):
        conn = self.get_conn()
        c = conn.cursor()
        q = "SELECT * FROM recipes WHERE 1=1"
        params = []
        if search:
            q += " AND (name LIKE ? OR ingredients LIKE ?)"
            params += [f"%{search}%", f"%{search}%"]
        if category and category not in ("Все блюда", "Все"):
            q += " AND category = ?"
            params.append(category)
        if cuisine and cuisine not in ("Все кухни", "Все"):
            q += " AND cuisine = ?"
            params.append(cuisine)
        if tag:
            q += " AND tags LIKE ?"
            params.append(f"%{tag}%")
        q += " ORDER BY cuisine, name"
        c.execute(q, params)
        rows = [dict(r) for r in c.fetchall()]
        conn.close()
        return rows

