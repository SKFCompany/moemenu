    def generate_shopping_list_for_week(self, monday):
        """
        Собирает ингредиенты всех рецептов, запланированных на неделю
        (учитываются только слоты меню, привязанные к настоящему рецепту —
        recipe_id заполняется при выборе рецепта из поиска в экране меню).
        Одинаковые ингредиенты из разных блюд объединяются в одну позицию
        с пометкой "×N". Продукты, которые уже есть в холодильнике, и то,
        что уже лежит в списке покупок, повторно не добавляются.

        Возвращает (added, already_have) — сколько позиций добавлено
        и сколько пропущено, потому что уже есть в холодильнике.
        """
        conn = self.get_conn()
        c = conn.cursor()
        days = [str(monday + timedelta(i)) for i in range(7)]
        placeholders = ",".join("?" * 7)
        c.execute(f"""SELECT DISTINCT recipe_id FROM meal_plan
                      WHERE plan_date IN ({placeholders}) AND recipe_id IS NOT NULL""", days)
        recipe_ids = [row["recipe_id"] for row in c.fetchall()]

        if not recipe_ids:
            conn.close()
            return 0, 0

        merged = {}  # lower-case ingredient -> {"name": исходное написание, "count": N}
        for rid in recipe_ids:
            c.execute("SELECT ingredients FROM recipes WHERE id = ?", (rid,))
            row = c.fetchone()
            if not row or not row["ingredients"]:
                continue
            for ing in row["ingredients"].split("|"):
                ing = ing.strip()
                if not ing:
                    continue
                key = ing.lower()
                entry = merged.setdefault(key, {"name": ing, "count": 0})
                entry["count"] += 1

        fridge = {r["name"].lower() for r in self.get_fridge()}
        c.execute("SELECT name FROM shopping_list")
        already_listed = {row["name"].lower() for row in c.fetchall()}

        added, already_have = 0, 0
        for key, entry in merged.items():
            if any(f in key or key in f for f in fridge):
                already_have += 1
                continue
            if key in already_listed:
                continue
            qty = f"×{entry['count']}" if entry["count"] > 1 else ""
            c.execute("INSERT INTO shopping_list (name, quantity) VALUES (?,?)",
                      (entry["name"], qty))
            added += 1

        conn.commit()
        conn.close()
        return added, already_have